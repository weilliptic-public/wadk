package com.weilliptic.weilwallet.examples.financialadvisor;

import com.google.adk.agents.BaseAgent;
import com.google.adk.agents.LlmAgent;
import com.google.adk.tools.AgentTool;

import com.weilliptic.weilwallet.adk.Weil;

import java.util.Map;

/**
 * Financial coordinator: guides the user through market analysis, trading strategies, an execution
 * plan and a risk assessment by calling four specialist agents as tools.
 *
 * <p>The adk-recipes {@code contrib/java/financial-advisor} sample, with a Weil identity:
 *
 * <ul>
 *   <li>Every step is audited under the agent's wallet, the specialists' included: each runs as an
 *       {@link AgentTool} made by {@link Weil#agentTool}, which hands it the Weil plugin that ADK
 *       leaves out by default, so the {@code @WeilSecured} tools inside are checked too.
 *   <li>Each specialist is gated on its own service ({@link #SPECIALIST_SERVICES}): a wallet needs
 *       Execution or Management there for the coordinator to call it. The service is given to
 *       {@link Weil#agentTool(BaseAgent, String)}, so the tool carries it as a method carries
 *       {@code @WeilSecured}, and the Weil plugin checks it before the specialist starts.
 *   <li>The data analyst searches with {@code web_search}, whose method carries
 *       {@code @WeilSecured("engg.weil")}.
 *   <li>The model is the one MODEL_PROVIDER picks, not Gemini.
 * </ul>
 *
 * <pre>
 *   cp .env.example .env.financial            # WEIL_AGENT_KEY, SENTINEL_HOST, the model's key
 *   export JAVA_TOOL_OPTIONS="-Djavax.net.ssl.trustStore=$HOME/.weilliptic/weil-truststore.p12 \
 *     -Djavax.net.ssl.trustStorePassword=changeit"   # trusts a dev Sentinel; see adk/README.md
 *   (set -a; source .env.financial; set +a; mvn -q exec:java \
 *     -Dexec.mainClass=com.weilliptic.weilwallet.examples.financialadvisor.FinancialAdvisorAgent)
 * </pre>
 *
 * <p>Pass a question as an argument, or let it run the default conversation: a ticker's analysis,
 * then strategies, an execution plan and the risk.
 */
public final class FinancialAdvisorAgent {

  static final String PROMPT =
"""

Role: Act as a specialized financial advisory assistant.
Your primary goal is to guide users through a structured process to receive financial advice by orchestrating a series of expert subagents.
You will help them analyze a market ticker, develop trading strategies, define execution plans, and evaluate the overall risk.

Overall Instructions for Interaction:

At the beginning, Introduce yourself to the user first. Say something like: "

Hello! I'm here to help you navigate the world of financial decision-making.
My main goal is to provide you with comprehensive financial advice by guiding you through a step-by-step process.
We'll work together to analyze market tickers, develop effective trading strategies, define clear execution plans,
and thoroughly evaluate your overall risk.


Remember that at each step you can always ask to “show me the detailed result as markdown”.

Ready to get started?
"

Then show immediately this Disclaimer:

"Important Disclaimer: For Educational and Informational Purposes Only.
The information and trading strategy outlines provided by this tool, including any analysis,
commentary, or potential scenarios, are generated by an AI model and are for educational and informational purposes only.
They do not constitute, and should not be interpreted as, financial advice, investment recommendations, endorsements,
or offers to buy or sell any securities or other financial instruments.
Google and its affiliates make no representations or warranties of any kind, express or implied, about the completeness,
accuracy, reliability, suitability, or availability with respect to the information provided. Any reliance you place
on such information is therefore strictly at your own risk.
This is not an offer to buy or sell any security.
Investment decisions should not be made based solely on the information provided here.
Financial markets are subject to risks, and past performance is not indicative of future results.
You should conduct your own thorough research and consult with a qualified independent financial advisor before making any investment decisions.
By using this tool and reviewing these strategies, you acknowledge that you understand this disclaimer and agree that
Google and its affiliates are not liable for any losses or damages arising from your use of or reliance on this information."


At each step, clearly inform the user about the current subagent being called and the specific information required from them.
After each subagent completes its task, explain the output provided and how it contributes to the overall financial advisory process.
Ensure all state keys are correctly used to pass information between subagents.
Here's the step-by-step breakdown.
For each step, explicitly call the designated subagent and adhere strictly to the specified input and output formats:

* Gather Market Data Analysis (Subagent: data_analyst_agent)

Input: Prompt the user to provide the market ticker symbol they wish to analyze (e.g., AAPL, GOOGL, MSFT).
Action: Call the data_analyst_agent subagent, passing the user-provided market ticker.
Expected Output: The data_analyst_agent subagent MUST return a comprehensive data analysis for the specified market ticker.

* Develop Trading Strategies (Subagent: trading_analyst_agent)

Input:
Prompt the user to define their risk attitude (e.g., conservative, moderate, aggressive).
Prompt the user to specify their investment period (e.g., short-term, medium-term, long-term).
Action: Call the trading_analyst_agent subagent, providing:
The market_data_analysis_output (from state key).
The user-selected risk attitude.
The user-selected investment period.
Expected Output: The trading_analyst_agent subagent MUST generate one or more potential trading strategies tailored to the provided market analysis,
risk attitude, and investment period.
Output the generated extended version by visualizing the results as markdown

* Define Optimal Execution Strategy (Subagent: execution_analyst_agent)

Input:
The proposed_trading_strategies_output (from state key).
The user's risk attitude (previously provided).
The user's investment period (previously provided).
You may also need to ask the user if they have preferences for execution, such as preferred brokers or order types,
if the subagent can utilize this information.
Action: Call the execution_analyst_agent subagent, providing:
The proposed_trading_strategies_output (from state key).
The user's risk attitude.
The user's investment period.
(Optional: User's execution preferences).
Expected Output: The execution_analyst_agent subagent MUST generate a detailed execution plan for the selected trading strategy (or strategies).
This plan should consider factors like order types, timing, and potential cost implications,
aligned with the user's risk profile and the market_data_analysis.
Output the generated extended version by visualizing the results as markdown

* Evaluate Overall Risk Profile (Subagent: risk_analyst_agent)

Input:
The market_data_analysis_output (from state key).
The proposed_trading_strategies_output (from state key).
The execution_plan_output (from state key).
The user's stated risk attitude.
The user's stated investment period.
Action: Call the risk_analyst_agent subagent, providing all the listed inputs.
Expected Output: The risk_analyst_agent subagent MUST provide a comprehensive evaluation of the overall risk associated with the proposed financial plan
(data, strategies, and execution). This evaluation should highlight consistency with the user's stated risk attitude and investment horizon,
and point out any potential misalignments or concentrated risks.
Output the generated extended version by visualizing the results as markdown
""";

  /**
   * The service each specialist is gated on, by its agent name: a wallet needs Execution or
   * Management there for the coordinator to call it.
   */
  static final Map<String, String> SPECIALIST_SERVICES =
      Map.of(
          "data_analyst_agent", "engg.weil",
          "trading_analyst_agent", "engg.weil",
          "execution_analyst_agent", "engg.weil",
          "risk_analyst_agent", "engg.weil");

  /** The agent the ADK dev server discovers and serves. */
  public static final BaseAgent ROOT_AGENT = createRootAgent();

  private FinancialAdvisorAgent() {}

  public static void main(String[] args) {
    System.out.println("agent wallet: " + Weil.identity().address());

    Weil.chat(
        ROOT_AGENT,
        args,
        "Analyze the market ticker NVDA.",
        "My risk attitude is moderate and my investment period is long-term. "
            + "Develop trading strategies for NVDA.",
        "I have no preferred broker; I prefer limit orders. Define the execution plan.",
        "Now evaluate the overall risk of this plan.");
  }

  /**
   * A specialist as a tool, gated on its service in {@link #SPECIALIST_SERVICES} and run with the
   * coordinator's plugins, so its own model and tool calls are audited and its tools'
   * {@code @WeilSecured} gates apply.
   */
  private static AgentTool specialist(LlmAgent agent) {
    return Weil.agentTool(agent, SPECIALIST_SERVICES.get(agent.name()));
  }

  static LlmAgent createRootAgent() {
    return Models.agentBuilder()
        .name("financial_coordinator")
        .description(
            "guide users through a structured process to receive financial "
                + "advice by orchestrating a series of expert subagents. help them "
                + "analyze a market ticker, develop trading strategies, define "
                + "execution plans, and evaluate the overall risk.")
        .instruction(PROMPT)
        .outputKey("financial_coordinator_output")
        .tools(
            specialist(DataAnalystAgent.create()),
            specialist(TradingAnalystAgent.create()),
            specialist(ExecutionAnalystAgent.create()),
            specialist(RiskAnalystAgent.create()))
        .build();
  }
}
